import assert from 'node:assert/strict';
import {createState} from '../dist/l3/thermal-physics.js';
import {validateCupPose,sweepCupPose,validateToolPose,sweepToolPose,benchRestPose} from '../dist/l3/thermal-spatial.js';
import {initialPositions,probePlacementAt,sampleFitsAt,targetAt} from '../dist/l3/thermal-apparatus.js';
import {validateCupPose as legacyCup} from '../dist/l3/thermal-collision.js';
let checks=0;const expect=(condition,label)=>{assert.ok(condition,label);checks++;};
const s=createState('ice');s.vesselPlaced=true;
expect(validateCupPose({x:120,y:130},0,s).valid,'Upright cup rests on its fixed stand');
expect(!validateCupPose({x:120,y:140},0,s).valid,'Cup cannot move through stand');
expect(!sweepCupPose({x:120,y:130},{x:120,y:130},{from:0,to:Math.PI/3},s).valid,'Tilt sweeps into stand before lifting');
expect(sweepCupPose({x:120,y:130},{x:120,y:70},0,s).valid,'Lift off stand');
expect(sweepCupPose({x:120,y:70},{x:360,y:70},0,s).valid,'High route reaches mouth');
expect(sweepCupPose({x:360,y:70},{x:360,y:70},{from:0,to:Math.PI/1.8},s).valid,'High tilt reaches100deg without wall contact');
expect(!validateCupPose({x:374,y:130},Math.PI/3,s).valid,'Spout may be over opening while body intersects calibrated wall');
expect(!sweepCupPose({x:550,y:300},{x:250,y:300},0,s).valid,'Fast move cannot tunnel through finite cylindrical wall');
expect(!validateCupPose({x:550,y:400},0,s).valid,'Whole body cannot cross bench');
// Actual cylinder-surface witness: a wall intersection invisible to XY-only checks.
const large=createState('ice',{capacityM3:.003});large.vesselPlaced=true;const p={x:425,y:220},a=Math.PI/2;
const inner=Math.sqrt(.003/(.176*32*Math.sin(2*Math.PI/64))),cupR=Math.sqrt(.0005/(.1*32*Math.sin(2*Math.PI/64)))+.002;
const actualRadius=Math.hypot(.015+.05,cupR);
expect(.065<inner&&actualRadius>inner&&actualRadius<inner+.004,'Independent actual cup surface lies inside annular wall although its X projection fits');
expect(legacyCup(p,a,{vesselPlaced:true}).valid,'Historical XY-only check misses radial witness');
expect(!validateCupPose(p,a,large).valid,'New3D envelope rejects radial witness');
const homes=initialPositions(s,.02);
for(const id of ['ice','solid','probe','stirrer','tongs','calorimeter'])expect(validateToolPose(id,homes[id],s,.02).valid,'Home pose '+id);
expect(!validateToolPose('ice',{x:660,y:homes.ice.y+5},s,.02).valid,'Ice cannot cross its tray');
expect(!validateToolPose('solid',{x:homes.solid.x,y:homes.solid.y+1},s,.02).valid,'Sample cannot cross bench');
expect(!sweepToolPose('ice',homes.ice,{x:410,y:300},s,.02).valid,'Ice cannot jump through sidewall');
expect(!sweepToolPose('ice',homes.ice,{x:660,y:120},s,.02).valid,'Ice cannot lift through the balance above its tray');
expect(sweepToolPose('ice',homes.ice,{x:575,y:homes.ice.y},s,.02).valid,'Slide out from underneath balance');
expect(sweepToolPose('ice',{x:575,y:homes.ice.y},{x:575,y:120},s,.02).valid,'Ice lifts through clear corridor');
expect(sweepToolPose('ice',{x:575,y:120},{x:410,y:120},s,.02).valid,'Ice above mouth');
expect(sweepToolPose('ice',{x:410,y:120},{x:410,y:300},s,.02).valid,'Centered piece fits through mouth');
expect(sampleFitsAt({x:410},s,'ice',.02),'20g physical cube fits600mL opening');
expect(!sampleFitsAt({x:450},s,'ice',.02),'Old wide target does not imply calibrated opening');
const small=createState('ice',{capacityM3:.0001});small.vesselPlaced=true;
expect(!sampleFitsAt({x:410},small,'ice',.02)&&sampleFitsAt({x:410},small,'ice',.001),'A1g cube fits mini vessel that rejects20g cube');
expect(targetAt({x:450,y:300},s)==='table','Drop outside new opening stays outside');
expect(targetAt({x:410,y:300},s)==='calorimeter','Valid drop at actual opening');
const wet=structuredClone(s);wet.waterMassKg=.2;
expect(probePlacementAt({x:410,y:300},wet,homes)==='water','Long probe can reach200mL water');
expect(probePlacementAt({x:410,y:346},wet,homes)==='wall','Touching bottom is not measuring free water');
expect(probePlacementAt({x:410,y:280},wet,homes)==='air','Air above surface is not mean water');
expect(!validateToolPose('probe',{x:444,y:300},s).valid,'Probe shaft cannot cross wall');
expect(!validateToolPose('probe',{x:410,y:350},s).valid,'Probe cannot cross vessel bottom');
expect(!validateToolPose('ice',homes.ice,s,NaN).valid,'Nonfinite piece cannot bypass guard');
const unplaced=createState('ice');
expect(!sweepToolPose('calorimeter',homes.calorimeter,{x:410,y:464},unplaced).valid,'Unplaced full vessel body cannot cross pedestal/bench');
expect(validateToolPose('calorimeter',{x:200,y:338},unplaced).valid,'Vessel resting on clear bench is allowed');
expect(benchRestPose({x:550,y:100},s)?.y>400,'A clear release rests on the bench');expect(benchRestPose({x:410,y:100},s)===null,'Do not silently push a sample through the vessel to reach the bench');
const before=structuredClone(s);validateCupPose({x:374,y:130},a,s);sweepToolPose('ice',homes.ice,{x:410,y:300},s);assert.deepEqual(s,before,'Guards never change physical state');
console.log(JSON.stringify({status:'PASS',checks,scope:'Literal calibrated paths, independent radial cylinder-surface witness, static supports, probe/drop domains and immutability. Conservative3D envelopes, not unconstrained rigid bodies or hardware acceptance.'}));
